function post(path, body, cookie='', clientIp) {
  const headers = {Origin:origin,'Content-Type':'application/json',Cookie:cookie}
  if (clientIp) headers['x-forwarded-for'] = clientIp
  return fetch(origin+path,{method:'POST',headers,body:JSON.stringify(body),redirect:'manual'})
}
function cookies(response) {
  return response.headers.getSetCookie().map(line=>line.split(';')[0]).join('; ')
}
async function challenge(key, expired=false) {
  const fields = {digest:createHmac('sha256',process.env.BETTER_AUTH_SECRET).update(key+':'+code).digest('hex'),attempts:0,expiresAt:new Date(Date.now()+(expired?-60000:60000))}
  await db.studentChallenge.upsert({where:{email:key},create:{email:key,...fields},update:fields})
}
